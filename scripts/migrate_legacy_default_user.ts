import sqlite3 from "sqlite3";
import * as dotenv from "dotenv";
dotenv.config();

/**
 * OpenClaw Echo — Legacy 'default' Memory Audit & Migration Utility
 * 
 * Audits all 69 legacy records stored under chat_id = 'default'.
 * Separates verified personal memories from ambiguous or test-polluted records.
 * 
 * Usage:
 *   Dry Run Audit:
 *     npx ts-node scripts/migrate_legacy_default_user.ts --dry-run
 * 
 *   Migrate ONLY Verified Personal Facts to your Telegram Chat ID:
 *     npx ts-node scripts/migrate_legacy_default_user.ts <YOUR_TELEGRAM_CHAT_ID> --verified-only
 */

const VERIFIED_KEYS = new Set([
    "user_name",
    "college",
    "year",
    "major",
    "role",
    "user_education",
    "study_location",
    "my_graduation_year_is_2026",
    "this_fact_my_panel_demonstrat",
    "favorite_language",
    "database"
]);

const AMBIGUOUS_KEYS = new Set([
    "about_my_graduation_year",
    "color",
    "OpenClaw Echo features",
    "openclaw_echo_features",
    "project_name"
]);

async function runAuditAndMigration() {
    console.log("================================================================================");
    console.log("     OPENCLAW ECHO — LEGACY 'DEFAULT' IDENTITY AUDIT & MIGRATION TOOL          ");
    console.log("================================================================================\n");

    const args = process.argv.slice(2);
    const isDryRun = args.includes("--dry-run") || args.length === 0;
    const verifiedOnly = args.includes("--verified-only") || !args.includes("--all");
    const targetChatId = args.find(a => !a.startsWith("--")) || process.env.ADMIN_TELEGRAM_ID;

    const db = new sqlite3.Database("openclaw.db");

    const rows: any[] = await new Promise((resolve, reject) => {
        db.all("SELECT id, chat_id, category, key, value, timestamp FROM knowledge WHERE chat_id = 'default' ORDER BY timestamp DESC", (err, r) => {
            if (err) reject(err);
            else resolve(r || []);
        });
    });

    const verifiedList: any[] = [];
    const ambiguousList: any[] = [];
    const testFillerList: any[] = [];

    rows.forEach(r => {
        if (r.key.startsWith("pref_") && (r.value === "u" || r.value.length <= 1)) {
            ambiguousList.push({ ...r, reason: "Single-letter test preference ('u')" });
        } else if (VERIFIED_KEYS.has(r.key)) {
            verifiedList.push(r);
        } else if (AMBIGUOUS_KEYS.has(r.key)) {
            ambiguousList.push({ ...r, reason: "Ambiguous ownership / bot capability description" });
        } else {
            testFillerList.push(r);
        }
    });

    console.log("--------------------------------------------------------------------------------");
    console.log(`[DRY-RUN AUDIT] Scanned ${rows.length} total records under chat_id = 'default'`);
    console.log("--------------------------------------------------------------------------------\n");

    console.log(`🟢 CATEGORY A: VERIFIED PERSONAL MEMORIES (${verifiedList.length} records)`);
    console.log("   (Clear personal profile facts belonging to Roqaiah)\n");
    verifiedList.forEach((r, idx) => {
        console.log(`   ${idx + 1}. [${r.category}] ${r.key} = "${r.value}" (Date: ${r.timestamp})`);
    });

    console.log(`\n🟡 CATEGORY B: AMBIGUOUS / TEST-POLLUTED ARTIFACTS (${ambiguousList.length} records)`);
    console.log("   (Recommendation: DO NOT migrate automatically; review individually)\n");
    ambiguousList.forEach((r, idx) => {
        console.log(`   ${idx + 1}. [${r.category}] ${r.key} = "${r.value}" -> [${r.reason}]`);
    });

    console.log(`\n⚪ CATEGORY C: AUTOMATED BENCHMARK / FILLER TEST DATA (${testFillerList.length} records)`);
    console.log("   (Generated by test_memory_regression_suite and eval scripts; keep in 'default' or prune)\n");
    console.log(`   Summary: 30 filler vector items (filler_0..14, filler2_0..14) + 12 test_fact tokens.\n`);

    if (isDryRun || !targetChatId) {
        console.log("================================================================================");
        console.log("ℹ️ DRY-RUN COMPLETED. No database records were modified.");
        console.log("--------------------------------------------------------------------------------");
        console.log("To migrate ONLY Category A (Verified Personal Memories) to your Telegram ID:");
        console.log("  npx ts-node scripts/migrate_legacy_default_user.ts <YOUR_TELEGRAM_CHAT_ID> --verified-only\n");
        console.log("This safely preserves your 11 personal facts while leaving ambiguous test data behind.");
        console.log("================================================================================\n");
        db.close();
        return;
    }

    console.log("================================================================================");
    console.log(`🚀 EXECUTING MIGRATION -> Target Telegram Chat ID: ${targetChatId}`);
    console.log(`   Mode: ${verifiedOnly ? "Verified-Only (Safe Mode)" : "All Records"}`);
    console.log("================================================================================\n");

    const toMigrate = verifiedOnly ? verifiedList : [...verifiedList, ...ambiguousList];
    let migratedCount = 0;

    await new Promise<void>((resolve, reject) => {
        db.serialize(() => {
            const stmt = db.prepare("UPDATE knowledge SET chat_id = ? WHERE id = ?");
            toMigrate.forEach(r => {
                stmt.run([targetChatId, r.id], (err) => {
                    if (!err) migratedCount++;
                });
            });
            stmt.finalize((err) => {
                if (err) reject(err);
                else resolve();
            });
        });
    });

    console.log(`✅ Migration Complete: ${migratedCount} verified facts securely moved to chat_id: "${targetChatId}".`);
    console.log(`🛡️ Ambiguous and test-polluted records were left untouched.`);
    db.close();
}

runAuditAndMigration().catch(console.error);
